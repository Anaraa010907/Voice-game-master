-- Friends: a public player number for search, friend requests, direct chat, room invites and gifts between friends.
-- Every write goes through the checked functions below; players read only their own rows.

-- A short number other players can search for (#100001 …).
alter table public.profiles add column if not exists player_no integer generated by default as identity (start with 100001);
create unique index if not exists profiles_player_no on public.profiles (player_no);
alter table public.profiles add column if not exists last_seen_at timestamptz;

create table if not exists public.friendships (
  user_low uuid not null references auth.users (id) on delete cascade,
  user_high uuid not null references auth.users (id) on delete cascade,
  requested_by uuid not null references auth.users (id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'accepted')),
  created_at timestamptz not null default now(),
  accepted_at timestamptz,
  primary key (user_low, user_high),
  check (user_low < user_high)
);
create index if not exists friendships_high on public.friendships (user_high);

create table if not exists public.direct_messages (
  id bigint generated always as identity primary key,
  sender uuid not null references auth.users (id) on delete cascade,
  recipient uuid not null references auth.users (id) on delete cascade,
  kind text not null default 'text' check (kind in ('text', 'invite', 'gift')),
  body text not null default '' check (char_length(body) <= 500),
  room_code text,
  gift_key text references public.shop_items (key),
  created_at timestamptz not null default now(),
  read_at timestamptz
);
create index if not exists direct_messages_pair on public.direct_messages (sender, recipient, created_at desc);
create index if not exists direct_messages_inbox on public.direct_messages (recipient, read_at, created_at desc);

alter table public.friendships enable row level security;
alter table public.direct_messages enable row level security;
revoke all on public.friendships, public.direct_messages from public, anon, authenticated;
grant all on public.friendships, public.direct_messages to service_role;
grant select on public.friendships, public.direct_messages to authenticated;

drop policy if exists "Players read their friendships" on public.friendships;
create policy "Players read their friendships" on public.friendships for select to authenticated
  using ((select auth.uid()) in (user_low, user_high));
drop policy if exists "Players read their messages" on public.direct_messages;
create policy "Players read their messages" on public.direct_messages for select to authenticated
  using ((select auth.uid()) in (sender, recipient));
-- Gifts a player sent or received outside a room (room_code 'DM').
drop policy if exists "Players see their own gifts" on public.gifts;
create policy "Players see their own gifts" on public.gifts for select to authenticated
  using ((select auth.uid()) in (from_user, to_user));

do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'direct_messages') then
    alter publication supabase_realtime add table public.direct_messages;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'friendships') then
    alter publication supabase_realtime add table public.friendships;
  end if;
end $$;

-- ---------- helpers ----------

create or replace function public.are_friends(p_a uuid, p_b uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.friendships where user_low = least(p_a, p_b) and user_high = greatest(p_a, p_b) and status = 'accepted');
$$;
revoke all on function public.are_friends(uuid, uuid) from public, anon, authenticated;

create or replace function public.touch_presence()
returns void
language sql
security definer
set search_path = ''
as $$
  update public.profiles set last_seen_at = now() where id = (select auth.uid());
$$;

-- ---------- search and the friend list ----------

create or replace function public.search_players(p_query text)
returns table (id uuid, display_name text, avatar_url text, avatar_key text, frame_key text, player_no integer, relation text)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
  needle text := lower(trim(both '#' from trim(coalesce(p_query, ''))));
begin
  if me is null then raise exception 'Нэвтэрнэ үү.' using errcode = '42501'; end if;
  if char_length(needle) < 2 then return; end if;
  return query
  select p.id, p.display_name, p.avatar_url, p.avatar_key, p.frame_key, p.player_no,
    case
      when f.status = 'accepted' then 'friend'
      when f.status = 'pending' and f.requested_by = me then 'outgoing'
      when f.status = 'pending' then 'incoming'
    end
  from public.profiles p
  left join public.friendships f on f.user_low = least(me, p.id) and f.user_high = greatest(me, p.id)
  where p.id <> me
    and (p.player_no::text = needle or strpos(lower(p.display_name), needle) > 0)
  order by (p.player_no::text = needle) desc, lower(p.display_name) = needle desc, p.display_name
  limit 20;
end;
$$;

create or replace function public.my_friends()
returns table (
  id uuid, display_name text, avatar_url text, avatar_key text, frame_key text, player_no integer,
  status text, incoming boolean, online boolean, room_code text, room_name text, game_type text, room_status text,
  unread integer, last_message_at timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
begin
  if me is null then raise exception 'Нэвтэрнэ үү.' using errcode = '42501'; end if;
  return query
  select p.id, p.display_name, p.avatar_url, p.avatar_key, p.frame_key, p.player_no,
    f.status, (f.status = 'pending' and f.requested_by <> me),
    coalesce(p.last_seen_at > now() - interval '2 minutes', false),
    r.room_code, r.name, r.game_type, r.status,
    (select count(*)::integer from public.direct_messages m where m.sender = p.id and m.recipient = me and m.read_at is null),
    (select max(m.created_at) from public.direct_messages m where (m.sender = p.id and m.recipient = me) or (m.sender = me and m.recipient = p.id))
  from public.friendships f
  join public.profiles p on p.id = case when f.user_low = me then f.user_high else f.user_low end
  left join lateral (
    select g.room_code, g.name, g.game_type, g.status from public.game_room_players s
    join public.game_rooms g on g.room_code = s.room_code
    where s.user_id = p.id and not s.is_bot
    order by g.updated_at desc limit 1
  ) r on f.status = 'accepted'
  where me in (f.user_low, f.user_high)
  order by (f.status = 'pending' and f.requested_by <> me) desc, coalesce(p.last_seen_at > now() - interval '2 minutes', false) desc, p.display_name;
end;
$$;

-- ---------- requests ----------

create or replace function public.send_friend_request(p_user uuid)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
  existing public.friendships;
begin
  if me is null then raise exception 'Нэвтэрнэ үү.' using errcode = '42501'; end if;
  if p_user = me then raise exception 'Өөртөө найзын хүсэлт илгээх боломжгүй.' using errcode = 'P0001'; end if;
  if not exists (select 1 from public.profiles where id = p_user) then raise exception 'Тоглогч олдсонгүй.' using errcode = 'P0002'; end if;
  select * into existing from public.friendships where user_low = least(me, p_user) and user_high = greatest(me, p_user);
  if found then
    if existing.status = 'accepted' then return 'friend'; end if;
    if existing.requested_by = me then return 'outgoing'; end if;
    -- They had already asked me: asking back accepts.
    update public.friendships set status = 'accepted', accepted_at = now() where user_low = existing.user_low and user_high = existing.user_high;
    return 'friend';
  end if;
  if (select count(*) from public.friendships where requested_by = me and created_at > now() - interval '1 day') >= 30 then
    raise exception 'Өдөрт 30-аас олон хүсэлт илгээх боломжгүй.' using errcode = 'P0001';
  end if;
  if (select count(*) from public.friendships where me in (user_low, user_high)) >= 200 then
    raise exception 'Найзын тоо хязгаартаа хүрсэн байна.' using errcode = 'P0001';
  end if;
  insert into public.friendships (user_low, user_high, requested_by) values (least(me, p_user), greatest(me, p_user), me);
  return 'outgoing';
end;
$$;

create or replace function public.respond_friend_request(p_user uuid, p_accept boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
begin
  if me is null then raise exception 'Нэвтэрнэ үү.' using errcode = '42501'; end if;
  if p_accept then
    update public.friendships set status = 'accepted', accepted_at = now()
    where user_low = least(me, p_user) and user_high = greatest(me, p_user) and status = 'pending' and requested_by = p_user;
    if not found then raise exception 'Хүсэлт олдсонгүй.' using errcode = 'P0002'; end if;
  else
    delete from public.friendships
    where user_low = least(me, p_user) and user_high = greatest(me, p_user) and status = 'pending';
  end if;
end;
$$;

-- Unfriend, or take back a request.
create or replace function public.remove_friend(p_user uuid)
returns void
language sql
security definer
set search_path = ''
as $$
  delete from public.friendships where user_low = least((select auth.uid()), p_user) and user_high = greatest((select auth.uid()), p_user);
$$;

-- ---------- chat ----------

create or replace function public.send_message(p_to uuid, p_body text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
  body text := trim(coalesce(p_body, ''));
  new_id bigint;
begin
  if me is null then raise exception 'Нэвтэрнэ үү.' using errcode = '42501'; end if;
  if not public.are_friends(me, p_to) then raise exception 'Зөвхөн найзтайгаа чатлах боломжтой.' using errcode = '42501'; end if;
  if char_length(body) = 0 then raise exception 'Мессеж хоосон байна.' using errcode = '22023'; end if;
  if (select count(*) from public.direct_messages where sender = me and created_at > now() - interval '1 minute') >= 20 then
    raise exception 'Хэт олон мессеж илгээлээ. Түр хүлээнэ үү.' using errcode = 'P0001';
  end if;
  insert into public.direct_messages (sender, recipient, body) values (me, p_to, left(body, 500)) returning id into new_id;
  return new_id;
end;
$$;

create or replace function public.mark_chat_read(p_from uuid)
returns void
language sql
security definer
set search_path = ''
as $$
  update public.direct_messages set read_at = now() where sender = p_from and recipient = (select auth.uid()) and read_at is null;
$$;

-- Invite a friend to the lobby I am sitting in. The invite also lets them past the room password.
create or replace function public.invite_friend(p_to uuid, p_room text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
  room public.game_rooms;
  new_id bigint;
begin
  if me is null then raise exception 'Нэвтэрнэ үү.' using errcode = '42501'; end if;
  if not public.are_friends(me, p_to) then raise exception 'Зөвхөн найзаа урих боломжтой.' using errcode = '42501'; end if;
  select * into room from public.game_rooms where room_code = p_room;
  if not found then raise exception 'Өрөө олдсонгүй.' using errcode = 'P0002'; end if;
  if not exists (select 1 from public.game_room_players where room_code = p_room and user_id = me) then
    raise exception 'Та энэ өрөөнд байхгүй байна.' using errcode = '42501';
  end if;
  if room.status <> 'lobby' then raise exception 'Тоглоом эхэлсэн тул урих боломжгүй.' using errcode = 'P0001'; end if;
  if (select count(*) from public.direct_messages where sender = me and kind = 'invite' and created_at > now() - interval '1 minute') >= 10 then
    raise exception 'Хэт олон урилга илгээлээ. Түр хүлээнэ үү.' using errcode = 'P0001';
  end if;
  insert into public.direct_messages (sender, recipient, kind, body, room_code)
  values (me, p_to, 'invite', left(room.name, 40), p_room) returning id into new_id;
  return new_id;
end;
$$;

-- ---------- gifts between friends (outside games) ----------

-- Emoji gifts, and frames or nameplates the friend does not own yet. Not while the sender is in a game.
create or replace function public.send_friend_gift(p_to uuid, p_key text)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
  item public.shop_items;
  sender_name text;
  receiver_name text;
  balance integer;
  cost integer;
begin
  if me is null then raise exception 'Нэвтэрнэ үү.' using errcode = '42501'; end if;
  if not public.are_friends(me, p_to) then raise exception 'Зөвхөн найздаа бэлэг илгээх боломжтой.' using errcode = '42501'; end if;
  if exists (select 1 from public.game_room_players s join public.game_rooms g on g.room_code = s.room_code
             where s.user_id = me and g.status = 'playing') then
    raise exception 'Тоглолтын үеэр хүрээ, нэрийн хавтан бэлэглэх боломжгүй. Тоглолт дууссаны дараа илгээнэ үү.' using errcode = 'P0001';
  end if;
  select * into item from public.shop_items where key = p_key and active and kind in ('gift', 'frame', 'nameplate');
  if not found then raise exception 'Бэлэг олдсонгүй.' using errcode = 'P0002'; end if;
  if item.kind <> 'gift' and exists (select 1 from public.player_items where user_id = p_to and item_key = p_key) then
    raise exception 'Найзад тань энэ бараа аль хэдийн байгаа.' using errcode = 'P0001';
  end if;
  if (select count(*) from public.gifts where from_user = me and created_at > now() - interval '1 minute') >= 10 then
    raise exception 'Хэт олон бэлэг илгээлээ. Түр хүлээнэ үү.' using errcode = 'P0001';
  end if;
  cost := case when public.is_admin() then 0 else item.price end;
  update public.profiles set coins = coins - cost where id = me and coins >= cost returning coins, display_name into balance, sender_name;
  if not found then raise exception 'Зоос хүрэлцэхгүй байна.' using errcode = 'P0001'; end if;
  select display_name into receiver_name from public.profiles where id = p_to;
  if item.kind <> 'gift' then
    insert into public.player_items (user_id, item_key) values (p_to, p_key);
  end if;
  insert into public.gifts (room_code, from_user, to_user, from_name, to_name, gift_key) values ('DM', me, p_to, sender_name, receiver_name, p_key);
  insert into public.direct_messages (sender, recipient, kind, body, gift_key) values (me, p_to, 'gift', item.name, p_key);
  return balance;
end;
$$;

